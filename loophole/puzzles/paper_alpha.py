"""Alpha 1.0 as used in Zhang, Belfer, Kry & Vouga, "C-Space Tunnel Discovery for Puzzle
Path Planning" (ACM TOG 39(4), SIGGRAPH 2020): two congruent alpha tubes (TetWild
remeshes of the classic Alpha puzzle), the OMPL problem file and the authors' solution
path. Fetched by scripts/fetch_alpha_paper.sh (pinned commit, sha256), never committed.

Conventions: OMPL problem file semantics (OBJ meshes, no up-axis conversion; the robot
is shifted by the mean of its vertices before the state is applied). Verified: with
this convention all 214 states of the authors' path are collision-free under FCL on the
raw meshes; other centring conventions put about half of them in collision.
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np

from .ompl_alpha import axis_angle_quat, parse_cfg, parse_path

REPO = Path(__file__).resolve().parents[2]
COMMIT = "cd05c5da442a526b13b0abb1c072e6e1c061aede"
SOURCE = f"https://gitlab.com/xinyazhang/puzzle-geometry/-/tree/{COMMIT}/puzzles/alpha"
FILES = {"cfg": "alpha-1.0.cfg", "robot": "alpha-1.0.dt.tcp.obj", "env": "alpha_env-1.0.dt.tcp.obj", "path": "alpha-1.0.ompl.txt"}
UNIT_SCALE = 0.04  # paper units -> metres: tubes ~2.5 m across (same scale as the OMPL.app task)
D_SEP_NATIVE = 10.0  # 0.4 m
PUZZLE_OUT = Path(__file__).resolve().parent / "alpha_paper"


def paper_dir() -> Path:
    return Path(os.environ.get("LOOPHOLE_ALPHA_PAPER_DIR", REPO / ".alpha_paper"))


def resolve_mesh_path(p: str) -> Path:
    f = paper_dir() / p[len("paper:") :]
    if not f.exists():
        raise FileNotFoundError(f"{f} missing: run `make fetch-alpha-paper` (fetched, never committed)")
    return f


def load_obj(path):
    import trimesh

    return trimesh.load(path, force="mesh", process=False)  # keep the vertex list as OMPL/Assimp sees it


def robot_center() -> np.ndarray:
    return np.asarray(load_obj(paper_dir() / FILES["robot"]).vertices).mean(axis=0)


def prepare() -> dict:
    """Derived meshes (robot re-centred, OMPL convention) and centre-lines, next to the fetched files."""
    d = paper_dir()
    rob = load_obj(d / FILES["robot"])
    c = np.asarray(rob.vertices).mean(axis=0)
    rob.apply_translation(-c)
    rob.export(d / "derived_robot.obj")
    load_obj(d / FILES["env"]).export(d / "derived_env.obj")
    if not (d / "derived_robot_centerline.npy").exists():
        prepare_centerlines()
    return {"robot_center_native": c.tolist()}


def solution_path_native() -> np.ndarray:
    """The authors' solution, (N, 7) x y z qw qx qy qz in paper units."""
    return parse_path(paper_dir() / FILES["path"])


def write_puzzle(config: dict, max_actions: int = 400, name: str = "alpha-1.0-paper") -> Path:
    import yaml

    d = paper_dir()
    cfg = parse_cfg(d / FILES["cfg"])
    meta = prepare()
    s = cfg["start"]
    spec = {
        "name": name,
        "difficulty": "hard",
        "description": "Alpha puzzle 1.0 (two identical interlocked alpha tubes), as in Zhang et al. 2020; separate them.",
        "max_actions": max_actions,
        "unit_scale": UNIT_SCALE,
        "gravity": [0.0, 0.0, 0.0],
        "floor": False,
        "frame": [{"name": "tube_a", "centerline": "paper:derived_env_centerline.npy",
                   "geoms": [{"type": "mesh", "path": "paper:derived_env.obj", "decompose": "facewedge"}]}],
        "objects": [{
            "name": "tube_b", "centerline": "paper:derived_robot_centerline.npy", "pos": s["xyz"], "quat": [float(v) for v in axis_angle_quat(s["theta"], s["axis"])],
            "graspable": True, "mass": 0.5, "damping": 2.0, "rgba": [0.2, 0.5, 0.9, 1.0],
            "geoms": [{"type": "mesh", "path": "paper:derived_robot.obj", "decompose": "facewedge"}],
        }],
        "target": "tube_b",
        "goal": {"type": "separation", "d_sep": D_SEP_NATIVE},
        "roadmap": f"roadmap-{name}.npz",
        "config": config,
        "meta": {
            "source": SOURCE,
            "paper": "X. Zhang, R. Belfer, P. G. Kry, E. Vouga. C-Space Tunnel Discovery for Puzzle Path Planning. ACM TOG 39(4), SIGGRAPH 2020",
            "licence": "derived from the OMPL.app Alpha puzzle (Rice licence: non-commercial, no redistribution); fetched, never committed",
            "files": FILES, "cfg_start": s, "cfg_goal": cfg.get("goal"), "cfg_volume": cfg["volume"],
            "robot_center_convention": "mean of OBJ vertices (OMPL)", "robot_center_native": meta["robot_center_native"],
        },
    }
    PUZZLE_OUT.mkdir(exist_ok=True)
    out = PUZZLE_OUT / f"{name}.yaml"
    out.write_text("# GENERATED by loophole.puzzles.paper_alpha.write_puzzle - poses/parameters only, no meshes.\n"
                   + yaml.safe_dump(spec, sort_keys=False, width=200))
    return out


def extract_centerline(mesh, n_out: int = 80) -> np.ndarray:
    """Centre-line polyline of a watertight tube mesh (same frame/units as the mesh).

    For every face, the ray along the inward normal crosses the tube's axis, so the
    midpoint between the face centroid and the opposite wall is an axis sample. The
    samples are ordered by the longest path of their minimum spanning tree (the tube
    is an open curve; strands at the alpha's crossing are much farther apart than
    neighbouring samples), lightly smoothed and resampled to `n_out` points.
    """
    import trimesh
    from scipy.sparse.csgraph import breadth_first_order, minimum_spanning_tree
    from scipy.spatial import cKDTree

    m = mesh.copy()
    m.merge_vertices(merge_tex=True, merge_norm=True)
    trimesh.repair.fix_normals(m)
    cen, n = m.triangles_center, m.face_normals
    eps = 1e-4 * float(np.linalg.norm(m.extents))
    loc, ray, _ = m.ray.intersects_location(cen - eps * n, -n, multiple_hits=False)
    axis = 0.5 * (cen[ray] + loc)
    tree = cKDTree(axis)
    d, j = tree.query(axis, k=12)
    from scipy.sparse import coo_matrix

    rows = np.repeat(np.arange(len(axis)), 11)
    g = coo_matrix((d[:, 1:].ravel() + 1e-12, (rows, j[:, 1:].ravel())), shape=(len(axis), len(axis))).tolil()
    # the kNN graph can split where long, thin triangles leave sparse samples: join
    # components through their closest pair of points until the graph is connected
    from scipy.sparse.csgraph import connected_components

    while True:
        ncomp, lab = connected_components(g, directed=False)
        if ncomp == 1:
            break
        best = None
        for c in range(1, ncomp):
            ia, ib = np.nonzero(lab == 0)[0], np.nonzero(lab == c)[0]
            dd, jj = cKDTree(axis[ia]).query(axis[ib])
            k_ = int(np.argmin(dd))
            if best is None or dd[k_] < best[0]:
                best = (dd[k_], ia[jj[k_]], ib[k_])
        g[best[1], best[2]] = best[0] + 1e-12
    g = g.tocsr()
    mst = minimum_spanning_tree(g.maximum(g.T))
    und = mst.maximum(mst.T)

    def farthest(src):
        order, pred = breadth_first_order(und, src, directed=False, return_predecessors=True)
        dist = np.zeros(len(axis))
        for v in order[1:]:
            dist[v] = dist[pred[v]] + np.linalg.norm(axis[v] - axis[pred[v]])
        return int(np.argmax(dist)), pred

    a, _ = farthest(0)
    b, pred = farthest(a)
    chain = [b]
    while chain[-1] != a:
        chain.append(pred[chain[-1]])
    pts = axis[chain]
    k = 7  # moving-average smoothing of the noisy axis samples
    pad = np.concatenate([np.repeat(pts[:1], k // 2, 0), pts, np.repeat(pts[-1:], k // 2, 0)])
    pts = np.array([pad[i : i + k].mean(0) for i in range(len(pts))])
    seg = np.linalg.norm(np.diff(pts, axis=0), axis=1)
    s = np.concatenate([[0], np.cumsum(seg)])
    t = np.linspace(0, s[-1], n_out)
    return np.stack([np.interp(t, s, pts[:, i]) for i in range(3)], axis=1)


def prepare_centerlines() -> dict:
    """Write centre-lines (native units, in the derived meshes' frames) next to the fetched files."""
    d = paper_dir()
    out = {}
    for key, fname in (("env", "derived_env.obj"), ("robot", "derived_robot.obj")):
        cl = extract_centerline(load_obj(d / fname))
        np.save(d / f"derived_{key}_centerline.npy", cl)
        out[key] = cl
    return out
